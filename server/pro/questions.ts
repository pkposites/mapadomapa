/** Versão pública: SEM pontos, SEM alertas de risco e SEM palavras-chave. */
export function publicQuestionnaire(slug: string) {
  return (QUESTIONNAIRES[slug] ?? []).map((qn) =>
    qn.kind === 'choice'
      ? { id: qn.id, kind: 'choice' as const, prompt: qn.prompt, options: qn.options.map(({ id, text }) => ({ id, text })) }
      : { id: qn.id, kind: 'open' as const, prompt: qn.prompt, hint: qn.hint },
  )
}

