// E2E local: roda no navegador (Chromium, tela de celular) contra `npm run dev`.
// Uso: node e2e/auth.e2e.cjs [pasta-de-capturas]   (requer: servidor em http://localhost:5173 e Playwright)
const { chromium } = require('playwright')
const { execSync } = require('node:child_process')
const B = process.env.BASE_URL ?? 'http://localhost:5173'
const SHOTS = process.argv[2]
const results = []
const check = (name, ok, extra = '') => { results.push({ name, ok }); console.log(`${ok ? '  ✓' : '  ✗'} ${name}${ok ? '' : '  ← ' + extra}`) }
const rnd = (n) => String(Math.floor(Math.random() * 10 ** n)).padStart(n, '0')
const newPhone = () => `(11) 9${rnd(4)}-${rnd(4)}`
const PASS = 'senha-forte-' + rnd(4)

async function smsCode(page, phoneDigits) {
  for (let i = 0; i < 20; i++) {
    const { messages } = await (await page.request.get(`${B}/api/dev/sms`)).json()
    const m = messages.find((x) => x.phone.endsWith(phoneDigits))
    if (m) return m.body.match(/\b(\d{6})\b/)[1]
    await page.waitForTimeout(250)
  }
  throw new Error('SMS simulado não apareceu')
}
const digits = (p) => p.replace(/\D/g, '')
const resetLimits = (page) => page.request.post(`${B}/api/dev/reset-limits`, { data: {} })
const bodyText = (page) => page.locator('body').innerText()

const robot = (page) => page.getByLabel(/Não sou um robô/).check()
async function overflow(page) { return page.evaluate(() => document.documentElement.scrollWidth - innerWidth) }

;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
  await ctx.addInitScript(() => localStorage.setItem('mdm_consent_v1', JSON.stringify({ marketing: false, at: 'teste' })))
  const page = await ctx.newPage()
  const errs = []
  page.on('pageerror', (e) => errs.push(String(e)))
  const shot = (n) => SHOTS && page.screenshot({ path: `${SHOTS}/${n}.png` })

  console.log('\n[1] Criação de conta (celular + senha + código por SMS)')
  const phone = newPhone()
  await resetLimits(page)
  await page.goto(B + '/')
  await page.getByRole('link', { name: 'Quero me cadastrar' }).first().click()
  await page.waitForURL('**/cadastro')
  await page.waitForSelector('text=Crie sua conta')
  check('CTA da landing leva ao cadastro real', true)
  check('pede e-mail', (await page.locator('input[type=email]').count()) === 1)
  await shot('01-cadastro')

  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForSelector('text=Digite o celular com DDD')
  check('formulário vazio mostra erros claros (inclui o CAPTCHA)', (await bodyText(page)).includes('pelo menos 8') && (await bodyText(page)).includes('não é um robô'))
  await shot('02-cadastro-erros')

  await page.getByLabel('Seu celular').fill(phone)
  await page.locator('input[type=email]').fill(digits(phone)+'@example.test')
  check('máscara do celular aplicada', (await page.getByLabel('Seu celular').inputValue()) === phone)
  await page.getByLabel('Crie uma senha').fill('12345678')
  await page.getByLabel(/Li e aceito/).check()
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForSelector('text=não é um robô')
  const smsBefore = (await (await page.request.get(`${B}/api/dev/sms`)).json()).messages.length
  check('sem marcar o CAPTCHA o cadastro não avança', (await page.locator('text=Confirme seu celular').count()) === 0)
  await robot(page)
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForSelector('text=fácil de adivinhar')
  check('nenhum SMS foi enviado com CAPTCHA ausente/senha fraca', (await (await page.request.get(`${B}/api/dev/sms`)).json()).messages.length === smsBefore)
  check('senha fraca é recusada com mensagem amigável', true)

  await page.getByLabel('Crie uma senha').fill(PASS)
  await robot(page)
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForSelector('text=Confirme seu celular')
  check('avança para a etapa do código', true)
  await shot('03-codigo')

  const code = await smsCode(page, digits(phone))
  const wrong = code === '000000' ? '111111' : '000000'
  await page.getByLabel('Código do SMS').fill(wrong)
  await page.getByRole('button', { name: 'Confirmar celular' }).click()
  await page.waitForSelector('text=Código incorreto')
  await page.waitForSelector('text=4 tentativas')
  check('código errado: mensagem + tentativas restantes', true)
  await shot('04-codigo-errado')

  await page.getByLabel('Código do SMS').fill(code)
  await page.getByRole('button', { name: 'Confirmar celular' }).click()
  await page.waitForURL('**/conta')
  check('código certo: conta criada e logada em /conta', (await page.getByTestId('account-phone').innerText()) === phone)
  await shot('05-conta')

  console.log('\n[2] Persistência de sessão e proteção de rotas')
  await page.reload()
  check('sessão sobrevive a recarregar a página', page.url().endsWith('/conta') && (await page.getByTestId('account-phone').innerText()) === phone)
  await page.goto(B + '/admin')
  await page.waitForSelector('text=não tem permissão')
  check('usuário comum em /admin vê "sem permissão"', true)
  await shot('06-admin-negado')
  const apiAdmin = await page.request.get(`${B}/api/admin/ping`)
  check('API admin recusa usuário comum (403)', apiAdmin.status() === 403, String(apiAdmin.status()))

  await page.goto(B + '/conta')
  await page.route('**/api/auth/logout', (r) => r.abort())
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await page.waitForSelector('text=Não foi possível sair agora')
  check('logout com falha de rede: avisa e NÃO finge que saiu (continua em /conta)', page.url().endsWith('/conta'))
  await page.unroute('**/api/auth/logout')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await page.waitForURL(B + '/')
  const anon = await ctx.newPage()
  await anon.goto(B + '/conta'); await anon.waitForURL('**/entrar')
  check('/conta sem login redireciona para /entrar', true)
  await anon.goto(B + '/admin'); await anon.waitForURL('**/entrar')
  check('/admin sem login redireciona para /entrar', true)
  check('API /me sem login = 401', (await anon.request.get(`${B}/api/auth/me`)).status() === 401)
  await anon.close()

  console.log('\n[3] Login correto e incorreto')
  await page.goto(B + '/entrar')
  await shot('07-entrar')
  await page.getByLabel('Seu celular').fill(phone)
  await page.getByLabel('Senha', { exact: true }).fill('senha-errada-999')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForSelector('text=Celular ou senha incorretos')
  check('senha errada: mensagem simples, sem revelar detalhes', true)
  await shot('08-login-errado')
  await page.getByLabel('Senha', { exact: true }).fill(PASS)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL('**/conta')
  check('senha certa entra em /conta', true)

  console.log('\n[4] Telefone duplicado')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await page.goto(B + '/cadastro')
  await page.getByLabel('Seu celular').fill(phone)
  await page.getByLabel('Crie uma senha').fill('outra-senha-forte-1')
  await page.getByLabel(/Li e aceito/).check()
  await robot(page)
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForSelector('text=já tem cadastro')
  check('número repetido: mensagem clara com link para Entrar', (await page.getByRole('link', { name: 'Entrar' }).count()) > 0)
  await shot('09-duplicado')

  console.log('\n[5] Recuperação de senha')
  await resetLimits(page)
  await page.goto(B + '/entrar')
  await page.getByRole('link', { name: 'Esqueci minha senha' }).click()
  await page.waitForURL('**/recuperar-senha')
  await shot('10-recuperar')
  await page.getByLabel('Seu celular').fill(phone)
  await robot(page)
  await page.getByRole('button', { name: 'Enviar código' }).click()
  await page.waitForSelector('text=Crie uma nova senha')
  await shot('11-recuperar-codigo')
  const rcode = await smsCode(page, digits(phone))
  const NEWPASS = 'nova-senha-forte-' + rnd(3)
  await page.getByLabel('Código do SMS').fill(rcode)
  await page.getByLabel('Nova senha').fill(NEWPASS)
  await page.getByRole('button', { name: 'Salvar nova senha' }).click()
  await page.waitForURL('**/entrar')
  await page.waitForSelector('text=Senha alterada')
  check('senha trocada: volta ao login com aviso de sucesso', true)
  await page.getByLabel('Seu celular').fill(phone)
  await page.getByLabel('Senha', { exact: true }).fill(PASS)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForSelector('text=Celular ou senha incorretos')
  check('senha ANTIGA deixa de funcionar', true)
  await page.getByLabel('Senha', { exact: true }).fill(NEWPASS)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL('**/conta')
  check('senha NOVA funciona', true)
  await page.getByRole('button', { name: 'Sair da conta' }).click()

  console.log('\n[6] Expiração do código')
  await resetLimits(page)
  const phone2 = newPhone()
  await page.goto(B + '/cadastro')
  await page.getByLabel('Seu celular').fill(phone2)
  await page.getByLabel('Crie uma senha').fill(PASS)
  await page.getByLabel(/Li e aceito/).check()
  await robot(page)
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForSelector('text=Confirme seu celular')
  const code2 = await smsCode(page, digits(phone2))
  await page.request.post(`${B}/api/dev/expire-codes`, { data: { phone: phone2 } })
  await page.getByLabel('Código do SMS').fill(code2)
  await page.getByRole('button', { name: 'Confirmar celular' }).click()
  await page.waitForSelector('text=Esse código venceu')
  check('código vencido é recusado com mensagem clara', true)
  await shot('12-codigo-vencido')
  check('botão de reenvio fica bloqueado durante o intervalo', await page.getByRole('button', { name: /Reenviar código em/ }).isDisabled())

  console.log('\n[7] Proteção contra tentativas abusivas')
  await resetLimits(page)
  await page.goto(B + '/entrar')
  for (let i = 0; i < 5; i++) {
    await page.getByLabel('Seu celular').fill(phone)
    await page.getByLabel('Senha', { exact: true }).fill('errada-' + i + '-xyz')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await page.waitForSelector('[role=alert]')
    await page.waitForTimeout(150)
  }
  await page.getByLabel('Senha', { exact: true }).fill(NEWPASS)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForSelector('text=Muitas tentativas')
  check('após 5 erros o login é bloqueado (mesmo com a senha certa)', page.url().endsWith('/entrar'))
  await shot('13-bloqueado')
  await resetLimits(page)

  console.log('\n[8] Administrador (permissão concedida no banco)')
  execSync(`npx netlify database connect --query "INSERT INTO user_roles (user_id, role_id) SELECT p.user_id, r.id FROM phones p, roles r WHERE p.e164 = '+55${digits(phone)}' AND r.name = 'admin' ON CONFLICT DO NOTHING"`, { stdio: 'pipe', timeout: 60000 })
  await page.goto(B + '/entrar')
  await page.getByLabel('Seu celular').fill(phone)
  await page.getByLabel('Senha', { exact: true }).fill(NEWPASS)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL('**/conta')
  await page.getByRole('link', { name: 'Área administrativa' }).waitFor()
  check('admin vê o atalho para a área administrativa', (await page.getByRole('link', { name: 'Área administrativa' }).count()) === 1)
  await page.getByRole('link', { name: 'Área administrativa' }).click()
  await page.waitForSelector('text=Permissão de administrador confirmada')
  check('admin acessa /admin (confirmado pelo servidor)', true)
  await shot('14-admin')
  await page.getByRole('link', { name: 'Voltar para minha conta' }).click()
  await page.getByRole('button', { name: 'Sair da conta' }).click()

  console.log('\n[9] Telas de celular: sem rolagem horizontal, botões e campos grandes')
  for (const w of [375, 390]) {
    await page.setViewportSize({ width: w, height: 812 })
    for (const path of ['/', '/cadastro', '/entrar', '/recuperar-senha']) {
      await page.goto(B + path); await page.waitForTimeout(300)
      const ov = await overflow(page)
      check(`${w}px ${path}: sem rolagem horizontal`, ov === 0, `+${ov}px`)
    }
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(B + '/entrar')
  const sizes = await page.evaluate(() => [...document.querySelectorAll('main input:not([type=checkbox]), main button[type=submit]')].map((e) => Math.round(e.getBoundingClientRect().height)))
  check('campos e botão principal têm ≥ 52px de altura', sizes.every((h) => h >= 52), sizes.join(','))
  const fonts = await page.evaluate(() => [...document.querySelectorAll('main input')].map((e) => parseFloat(getComputedStyle(e).fontSize)))
  check('texto dos campos ≥ 16px (sem zoom automático no iPhone)', fonts.every((f) => f >= 16), fonts.join(','))
  console.log('\n[9b] Pré-cadastro x abertura dos pedidos')
  const closedPage = await ctx.newPage()
  await closedPage.route('**/api/status', (r) => r.fulfill({ json: { preRegistrationOpen: false } }))
  await closedPage.goto(B + '/cadastro')
  await closedPage.waitForSelector('text=O pré-cadastro abre em breve')
  check('pré-cadastro fechado: mostra aviso e a data dos pedidos, sem formulário', (await closedPage.locator('input').count()) === 0 && (await closedPage.locator('body').innerText()).includes('25/11/2026'))
  await closedPage.close()
  await page.goto(B + '/')
  const landingText = (await page.locator('body').innerText()).replace(/\s+/g, ' ')
  check('landing diz "Pedidos de orçamento abrem em 25/11/2026"', /pedidos de orçamento abrem em/i.test(landingText) && landingText.includes('25/11/2026'))
  check('landing explica que o pré-cadastro é gratuito e a data é dos pedidos', /o pré-cadastro é gratuito/i.test(landingText) && /abertura dos pedidos/i.test(landingText))

  console.log('\n[10] Landing pública e cabeçalho')
  const anonCtx = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await anonCtx.addInitScript(() => localStorage.setItem('mdm_consent_v1', JSON.stringify({ marketing: false, at: 'teste' })))
  const anonPage = await anonCtx.newPage()
  const apiCalls = []
  anonPage.on('request', (r) => { if (r.url().includes('/api/auth/me')) apiCalls.push(r.url()) })
  await anonPage.goto(B + '/'); await anonPage.waitForTimeout(800)
  check('visitante anônimo na landing NÃO chama a API (sem custo de função)', apiCalls.length === 0, String(apiCalls.length))
  check('cabeçalho mostra "Cadastrar" para visitante', (await anonPage.getByRole('link', { name: 'Cadastrar' }).count()) > 0)
  await anonCtx.close()
  await page.goto(B + '/entrar')
  await page.getByLabel('Seu celular').fill(phone)
  await page.getByLabel('Senha', { exact: true }).fill(NEWPASS)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL('**/conta')
  await page.goto(B + '/')
  await page.getByRole('link', { name: 'Minha conta' }).waitFor()
  check('logado, o cabeçalho da landing mostra "Minha conta"', true)
  await page.goto(B + '/conta'); await page.getByRole('button', { name: 'Sair da conta' }).click()

  check('sem erros de JavaScript durante todo o teste', errs.length === 0, errs.join(' | '))

  await browser.close()
  const failed = results.filter((r) => !r.ok)
  console.log(`\n${results.length - failed.length}/${results.length} verificações passaram${failed.length ? ' — FALHARAM: ' + failed.map((f) => f.name).join('; ') : ''}`)
  process.exit(failed.length ? 1 : 0)
})().catch((e) => { console.error('ERRO NO TESTE:', e.message); process.exit(2) })
